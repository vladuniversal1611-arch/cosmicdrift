    const d = this.D[this.lang] || this.D.en;
    let s = d[key] !== undefined ? d[key] : this.D.en[key];
    if (s === undefined) s = key;
    if (vars) for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
    return s;
